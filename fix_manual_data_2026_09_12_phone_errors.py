from company_agent import connect_sheets

# Индексы колонок (0-based, см. add_company() в company_agent.py):
COL_NAME = 1
COL_PHONE = 10
COL_AVATAR = 15

FIXES = {
    "Winner Auto Club": {
        COL_PHONE: "+995 511 299 299",
    },
    "Todes-Avto": {
        COL_PHONE: "+7 (800) 777-51-96",
    },
    "AUTOCOM": {
        COL_PHONE: "+375 (29) 666-62-86",
    },
    "ES Transit Premium": {
        COL_PHONE: "+7 (908) 444-00-14",
    },
    "Artalex Group": {
        COL_PHONE: "+48793576146",
    },
    "AutoShoot": {
        COL_AVATAR: "https://autoshoot.ru/wp-content/uploads/2026/04/12345.png",
    },
}


def main():
    ws = connect_sheets()
    all_values = ws.get_all_values()

    for name, fields in FIXES.items():
        row_num = None
        for i, row in enumerate(all_values[1:], start=2):
            if len(row) > COL_NAME and row[COL_NAME].strip() == name:
                row_num = i
                break
        if row_num is None:
            print(f"ПРОПУСК (не найдена): {name}")
            continue
        for col_idx, value in fields.items():
            ws.update_cell(row_num, col_idx + 1, value)  # gspread — 1-based колонки
        changed = ", ".join(f"{v!r}" for v in fields.values())
        print(f"Обновлена строка {row_num}: {name!r} -> {changed}")

    print("Готово. Дальше: python3 update_site.py")
    print("Не забыть вручную: колонка «Телефон» в Google Sheets -> Формат -> "
          "Число -> Обычный текст (иначе баг может вернуться при следующем "
          "ручном редактировании номера с '+').")


if __name__ == "__main__":
    main()
